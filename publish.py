"""Platform publishing. Each function is a STUB until the matching account is connected and its
GitHub Secrets are set (see /template/../ACCOUNTS.md, generated by setup_accounts.py once the name is confirmed).
watchdog.py and run_day.py never call the platform APIs directly - they always go through here, so
connecting a real account later means filling in ONE function, nothing else changes."""
import os, json, datetime as dt

class NotConnected(Exception):
    pass

def _need(*names):
    missing = [n for n in names if not os.environ.get(n)]
    if missing: raise NotConnected(f"missing secrets: {', '.join(missing)}")

def publish_facebook_reel(video_path, caption): _need("FB_PAGE_ID", "FB_PAGE_TOKEN"); raise NotConnected("Facebook not connected yet")
def publish_facebook_post(image_path, caption): _need("FB_PAGE_ID", "FB_PAGE_TOKEN"); raise NotConnected("Facebook not connected yet")
def publish_instagram_reel(video_path, caption): _need("IG_USER_ID", "FB_PAGE_TOKEN"); raise NotConnected("Instagram not connected yet")
def publish_instagram_post(image_path, caption): _need("IG_USER_ID", "FB_PAGE_TOKEN"); raise NotConnected("Instagram not connected yet")
def publish_instagram_story(image_path): _need("IG_USER_ID", "FB_PAGE_TOKEN"); raise NotConnected("Instagram not connected yet")
def publish_facebook_story(image_path): _need("FB_PAGE_ID", "FB_PAGE_TOKEN"); raise NotConnected("Facebook not connected yet")
def publish_tiktok(video_path, caption): _need("TIKTOK_REFRESH_TOKEN"); raise NotConnected("TikTok not connected yet (drafts-only until app review passes)")
def publish_youtube_short(video_path, caption): _need("YT_REFRESH_TOKEN", "YT_CHANNEL_ID"); raise NotConnected("YouTube not connected yet")

DISPATCH = {
    "facebook_reel": publish_facebook_reel, "facebook_post": publish_facebook_post, "facebook_story": publish_facebook_story,
    "instagram_reel": publish_instagram_reel, "instagram_post": publish_instagram_post, "instagram_story": publish_instagram_story,
    "tiktok": publish_tiktok, "youtube_short": publish_youtube_short,
}

def publish(platform, item, files, caption):
    """files: dict with 'video' and/or 'image' paths already rendered for this item. Returns (ok, detail)."""
    fn = DISPATCH[platform]
    path = files.get("video") if "video" in platform or platform == "tiktok" or platform.endswith("_reel") else files.get("image", files.get("video"))
    try:
        args = (path, caption) if fn.__code__.co_argcount == 2 else (path,)
        ref = fn(*args)
        return True, {"platform_ref": ref}
    except NotConnected as e:
        return False, {"error": "not_connected", "message": str(e)}
    except Exception as e:
        return False, {"error": "publish_failed", "message": str(e)}
