"""Platform publishing. Each function is a STUB until the matching account is connected and its
GitHub Secrets are set (see /template/../ACCOUNTS.md, generated by setup_accounts.py once the name is confirmed).
watchdog.py and run_day.py never call the platform APIs directly - they always go through here, so
connecting a real account later means filling in ONE function, nothing else changes."""
import os, json, datetime as dt

class NotConnected(Exception):
    pass

def _need(*names):
    missing = [n for n in names if not os.environ.get(n)]
    if missing: raise NotConnected(f"missing secrets: {', '.join(missing)}")

# Each function receives the file(s) already rendered for this platform (render_day.py made them) and the
# caption. Video/post/story platforms get one path; carousel platforms get a LIST of image paths (in order).
# Fill in the real API call inside each function once that platform's account is connected and its secrets
# are set - nothing else in the pipeline (selector, render_day, watchdog) needs to change.
def publish_facebook_reel(path, caption): _need("FB_PAGE_ID", "FB_PAGE_TOKEN"); raise NotConnected("Facebook not connected yet")
def publish_facebook_post(path, caption): _need("FB_PAGE_ID", "FB_PAGE_TOKEN"); raise NotConnected("Facebook not connected yet")
def publish_facebook_story(path, caption): _need("FB_PAGE_ID", "FB_PAGE_TOKEN"); raise NotConnected("Facebook not connected yet")
def publish_facebook_carousel(paths, caption): _need("FB_PAGE_ID", "FB_PAGE_TOKEN"); raise NotConnected("Facebook not connected yet")
def publish_instagram_reel(path, caption): _need("IG_USER_ID", "FB_PAGE_TOKEN"); raise NotConnected("Instagram not connected yet")
def publish_instagram_post(path, caption): _need("IG_USER_ID", "FB_PAGE_TOKEN"); raise NotConnected("Instagram not connected yet")
def publish_instagram_story(path, caption): _need("IG_USER_ID", "FB_PAGE_TOKEN"); raise NotConnected("Instagram not connected yet")
def publish_instagram_carousel(paths, caption): _need("IG_USER_ID", "FB_PAGE_TOKEN"); raise NotConnected("Instagram not connected yet")
def publish_tiktok(path, caption): _need("TIKTOK_REFRESH_TOKEN"); raise NotConnected("TikTok not connected yet (drafts-only until app review passes)")
def publish_youtube_short(path, caption): _need("YT_REFRESH_TOKEN", "YT_CHANNEL_ID"); raise NotConnected("YouTube not connected yet")

DISPATCH = {
    "facebook_reel": publish_facebook_reel, "facebook_post": publish_facebook_post, "facebook_story": publish_facebook_story,
    "facebook_carousel": publish_facebook_carousel,
    "instagram_reel": publish_instagram_reel, "instagram_post": publish_instagram_post, "instagram_story": publish_instagram_story,
    "instagram_carousel": publish_instagram_carousel,
    "tiktok": publish_tiktok, "youtube_short": publish_youtube_short,
}

def publish(platform, path_or_paths, caption):
    """path_or_paths: the file (or, for *_carousel platforms, the ordered list of files) render_day.py made.
    Returns (ok, detail)."""
    try:
        ref = DISPATCH[platform](path_or_paths, caption)
        return True, {"platform_ref": ref}
    except NotConnected as e:
        return False, {"error": "not_connected", "message": str(e)}
    except Exception as e:
        return False, {"error": "publish_failed", "message": str(e)}
